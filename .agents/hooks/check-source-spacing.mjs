/**
 * Checks that control-flow statements form separate visual paragraphs.
 *
 * Biome preserves blank lines but cannot infer where a function changes phase.
 * This check enforces the syntactic part of that convention. Logical grouping
 * among declarations remains an agent-review concern.
 */
import { parseSync } from 'oxc-parser';

const SOURCE_EXTENSION = /\.(?:[cm]?[jt]sx?)$/;
const EXCLUDED_PATH = /(?:^|\/)(?:dist|types|__generated__|fixtures)(?:\/|$)/;
const GENERATED_HEADER = /^\/\*\* Generated by /;
const CONTROL_FLOW_TYPES = new Set([
  'DoWhileStatement',
  'ForInStatement',
  'ForOfStatement',
  'ForStatement',
  'IfStatement',
  'SwitchStatement',
  'TryStatement',
  'WhileStatement',
]);
const STATEMENT_LIST_TYPES = new Set(['BlockStatement', 'Program', 'StaticBlock', 'TSModuleBlock']);

function isControlFlowStatement(statement) {
  while (statement?.type === 'LabeledStatement') statement = statement.body;

  return CONTROL_FLOW_TYPES.has(statement?.type);
}

function hasBlankLine(source, previous, current, comments) {
  const between = source.slice(previous.end, current.start);

  for (const match of between.matchAll(/\r?\n[\t ]*\r?\n/g)) {
    const start = previous.end + match.index;
    const end = start + match[0].length;
    const insideComment = comments.some((comment) => start >= comment.start && end <= comment.end);

    if (!insideComment) return true;
  }

  return false;
}

function statementName(statement) {
  while (statement?.type === 'LabeledStatement') statement = statement.body;

  return statement?.type.replace(/Statement$/, '') ?? 'statement';
}

function lineNumberAt(source, offset) {
  let line = 1;

  for (let index = 0; index < offset; index++) {
    if (source.charCodeAt(index) === 10) line++;
  }

  return line;
}

function createFix(source, previous, current, comments) {
  const previousLineEnd = source.indexOf('\n', previous.end);
  const trailingComment = comments
    .filter((comment) => comment.start >= previous.end && comment.end <= current.start)
    .findLast((comment) => previousLineEnd === -1 || comment.start < previousLineEnd);
  const anchor = trailingComment?.end ?? previous.end;
  const newlineOffset = source.indexOf('\n', anchor);

  if (newlineOffset !== -1 && newlineOffset < current.start) {
    return { end: newlineOffset + 1, start: newlineOffset + 1 };
  }

  const lineStart = source.lastIndexOf('\n', previous.start - 1) + 1;
  const indent = source.slice(lineStart, previous.start).match(/^[\t ]*/)?.[0] ?? '';

  return { end: current.start, indent, start: previous.end };
}

export function isSourcePath(path) {
  return SOURCE_EXTENSION.test(path) && !EXCLUDED_PATH.test(path);
}

export function isGeneratedSource(source) {
  return GENERATED_HEADER.test(source);
}

export function analyzeSource(filePath, source) {
  const parsed = parseSync(filePath, source);
  const violations = [];

  function inspectStatementList(statements) {
    for (let index = 1; index < statements.length; index++) {
      const previous = statements[index - 1];
      const current = statements[index];

      if (
        (isControlFlowStatement(previous) || isControlFlowStatement(current)) &&
        !hasBlankLine(source, previous, current, parsed.comments)
      ) {
        violations.push({
          current: statementName(current),
          fix: createFix(source, previous, current, parsed.comments),
          line: lineNumberAt(source, current.start),
          previous: statementName(previous),
        });
      }
    }
  }

  function visit(node) {
    if (!node || typeof node !== 'object') return;

    if (STATEMENT_LIST_TYPES.has(node.type)) inspectStatementList(node.body);

    if (node.type === 'SwitchCase') inspectStatementList(node.consequent);

    for (const value of Object.values(node)) {
      if (Array.isArray(value)) {
        for (const child of value) visit(child);
      } else {
        visit(value);
      }
    }
  }

  visit(parsed.program);

  return { errors: parsed.errors, violations };
}

export function fixSource(source, violations) {
  const newline = source.includes('\r\n') ? '\r\n' : '\n';
  const fixes = [
    ...new Map(violations.map((violation) => [`${violation.fix.start}:${violation.fix.end}`, violation.fix])).values(),
  ].sort((a, b) => b.start - a.start);

  for (const fix of fixes) {
    const replacement = fix.indent === undefined ? newline : `${newline}${newline}${fix.indent}`;

    source = `${source.slice(0, fix.start)}${replacement}${source.slice(fix.end)}`;
  }

  return source;
}
